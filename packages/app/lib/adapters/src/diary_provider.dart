/// A provider that creates a [DiaryCommand] instance.
///
/// {@macro diary.DiaryCommand}
@Riverpod(keepAlive: true)
DiaryCommand diaryCommand(Ref ref) {
  final dbClient = ref.watch(dbClientProvider);
  return DiaryCommand(dbClient: dbClient);
}

/// A provider that creates a [DiaryQuery] instance.
///
/// {@macro diary.DiaryQuery}
@Riverpod(keepAlive: true)
DiaryQuery diaryQuery(Ref ref) {
  final dbClient = ref.watch(dbClientProvider);
  return DiaryQuery(dbClient: dbClient);
}

/// Provides the diary images whose photo data is outside the app.
///
/// This is not a stream, because a paused stream keeps the database from
/// closing during a restore.
@riverpod
Future<List<DiaryImage>> externalDiaryImages(Ref ref) {
  final query = ref.watch(diaryQueryProvider);
  return query.getExternalDiaryImages();
}

/// Provides a list of diaries within the specified date range.
@riverpod
Future<List<Diary>> diaries(
  // Changed `from` to `fromDate`/`toDate` to avoid conflict with code generated by Riverpod Generator.
  Ref ref, {
  required DateTime fromDate,
  required DateTime toDate,
}) async {
  final query = ref.watch(diaryQueryProvider);
  return query.getDiaries(from: fromDate, to: toDate);
}

/// Type definition for a list of diaries with dates.
typedef DiariesWithDates = ({List<Diary> diaries, List<DateTime> dates});

/// Provides a list of diaries with dates within the specified date range.
@riverpod
class CachedDiaries extends _$CachedDiaries {
  final DateTime _now = clock.now();

  DiaryCommand get _diaryCommand => ref.read(diaryCommandProvider);

  DiaryImageCommand get _imageCommand => ref.read(diaryImageCommandProvider);

  /// Runs one load of each direction at a time, so that calls during a load
  /// wait for it instead of loading the same month again.
  final _olderLoad = AsyncCache<void>.ephemeral();
  final _newerLoad = AsyncCache<void>.ephemeral();

  @override
  Future<DiariesWithDates> build() async {
    final dates = _now.datesInMonths(-1, 1);
    final diaries = await ref.watch(
      diariesProvider(fromDate: dates.first, toDate: dates.last).future,
    );
    return (diaries: diaries, dates: dates);
  }

  /// Loads the diaries of the month before the loaded dates.
  Future<void> loadMoreOlder() => _olderLoad.fetch(_loadOlder);

  /// Loads the diaries of the month after the loaded dates.
  Future<void> loadMoreNewer() => _newerLoad.fetch(_loadNewer);

  Future<void> _loadOlder() async {
    if (state.isLoading || !state.hasValue) {
      // Do nothing if the state is loading or has no value.
      return;
    }
    final month = state.requireValue.dates.first.previousMonthDates;
    final diaries = await _diariesIn(month);
    final latest = state.requireValue;
    state = AsyncValue.data((
      diaries: [...diaries, ...latest.diaries],
      dates: [...month, ...latest.dates],
    ));
  }

  Future<void> _loadNewer() async {
    if (state.isLoading || !state.hasValue) {
      // Do nothing if the state is loading or has no value.
      return;
    }
    final month = state.requireValue.dates.last.nextMonthDates;
    final diaries = await _diariesIn(month);
    final latest = state.requireValue;
    state = AsyncValue.data((
      diaries: [...latest.diaries, ...diaries],
      dates: [...latest.dates, ...month],
    ));
  }

  Future<List<Diary>> _diariesIn(List<DateTime> month) {
    return ref.read(
      diariesProvider(fromDate: month.first, toDate: month.last).future,
    );
  }

  /// Add a new diary entry.
  Future<void> addDiary({
    required DateTime date,
    required String content,
  }) async {
    // Cannot use unawaited for optimistic update
    // because Diary ID is needed for state update.
    final entry = await _diaryCommand.addDiary(date: date, content: content);
    final diary = Diary(entry: entry, images: const []);
    final current = state.requireValue;
    state = AsyncValue.data((
      diaries: [...current.diaries, diary],
      dates: current.dates,
    ));
  }

  /// Update an existing diary entry.
  Future<void> updateDiary({required int id, required String content}) async {
    unawaited(_diaryCommand.updateDiary(id: id, content: content));
    final current = state.requireValue;
    final updatedDiaries = current.diaries.map((diary) {
      final entry = diary.entry;
      if (entry.id == id) {
        return diary.copyWith(
          entry: entry.copyWith(content: content),
        );
      }
      return diary;
    }).toList();
    state = AsyncValue.data((diaries: updatedDiaries, dates: current.dates));
  }

  /// Add the photo at [path] to the diary entry of [date].
  ///
  /// Adds the entry to the state when the date had none.
  Future<void> addImage({
    required DateTime date,
    required String path,
  }) async {
    final fileName = await _imageCommand.storePhoto(path);
    // Cannot use unawaited for optimistic update
    // because the diary entry and its image are needed for state update.
    final (:entry, :image) = await _imageCommand.addDiaryImage(
      date: date,
      fileName: fileName,
    );

    final current = state.requireValue;
    final hasDiary = current.diaries.any((d) => d.entry.id == entry.id);
    final updatedDiaries = hasDiary
        ? current.diaries.map((d) {
            if (d.entry.id == entry.id) {
              return d.copyWith(images: [...d.images, image]);
            }
            return d;
          }).toList()
        : [
            ...current.diaries,
            Diary(entry: entry, images: [image]),
          ];

    state = AsyncValue.data((diaries: updatedDiaries, dates: current.dates));
  }

  /// Delete an image from a diary entry.
  Future<void> deleteImage({required int imageId}) async {
    unawaited(_imageCommand.deleteDiaryImage(id: imageId));
    final current = state.requireValue;
    final updatedDiaries = current.diaries.map((diary) {
      return diary.copyWith(
        images: diary.images.where((img) => img.id != imageId).toList(),
      );
    }).toList();
    state = AsyncValue.data((diaries: updatedDiaries, dates: current.dates));
  }

  /// Delete the images whose photo data is outside the app.
  Future<void> deleteExternalImages() async {
    await _imageCommand.deleteExternalDiaryImages();
    final current = state.requireValue;
    final updatedDiaries = current.diaries.map((diary) {
      return diary.copyWith(
        images: diary.images
            .where((img) => img.fileName != null || img.photoId == null)
            .toList(),
      );
    }).toList();
    state = AsyncValue.data((diaries: updatedDiaries, dates: current.dates));
  }
}

/// The minimum length of a diary search term.
///
/// {@macro diary.DiaryQuery.minSearchTermLength}
@Riverpod(keepAlive: true)
int minDiarySearchTermLength(Ref ref) {
  final diaryQuery = ref.watch(diaryQueryProvider);
  return diaryQuery.minSearchTermLength;
}

/// The text the user entered in the diary search, the term searched from it,
/// and how far the results of the term are scrolled.
typedef DiarySearchPlace = ({String input, String term, double scrollOffset});

/// {@template onepage.DiarySearchSession}
/// The diary search that the search dialog shows, kept until the app closes
/// so that the dialog opens again where the user left it.
///
/// The term is the input without the spaces around it, and is empty when
/// nothing is searched.
/// {@endtemplate}
@Riverpod(keepAlive: true)
class DiarySearchSession extends _$DiarySearchSession {
  int get _minDiarySearchTermLength =>
      ref.read(minDiarySearchTermLengthProvider);

  RecentDiarySearchTerms get _recentDiarySearchTermsNotifier =>
      ref.read(recentDiarySearchTermsProvider.notifier);

  @override
  DiarySearchPlace build() => (input: '', term: '', scrollOffset: 0);

  /// Searches the term in [input].
  ///
  /// Searches nothing when the term is shorter than
  /// [minDiarySearchTermLength]. Keeps how far the results are scrolled when
  /// the term is the term already searched, and starts from the top of them
  /// otherwise.
  void search(String input) {
    final trimmed = input.trim();
    final isSearchable = trimmed.length >= _minDiarySearchTermLength;
    final term = isSearchable ? trimmed : '';
    final isSameTerm = term == state.term;
    final scrollOffset = isSameTerm ? state.scrollOffset : 0.0;
    state = (input: input, term: term, scrollOffset: scrollOffset);
  }

  /// Saves how far the results of the term are scrolled.
  void saveScrollOffset(double scrollOffset) {
    state = (input: state.input, term: state.term, scrollOffset: scrollOffset);
  }

  /// Adds the searched term to [RecentDiarySearchTerms].
  ///
  /// Does nothing when nothing is searched.
  Future<void> addTermToRecent() async {
    if (state.term.isEmpty) {
      return;
    }
    await _recentDiarySearchTermsNotifier.add(state.term);
  }
}

/// The diary entries loaded for a search, and whether more of them are left.
typedef LoadedDiaryEntries = ({List<DiaryEntry> entries, bool hasMore});

/// {@template onepage.DiarySearchResults}
/// The diary entries that contain a search term, the newest first, loaded
/// a page at a time.
///
/// The results of the term of [DiarySearchSession] stay after the search
/// dialog closes, and the others are disposed when nothing watches them.
/// An empty term has no entries, and searches nothing.
/// A failure to load more entries keeps the loaded ones in the state.
/// {@endtemplate}
@riverpod
class DiarySearchResults extends _$DiarySearchResults {
  static const _pageSize = 20;

  static const LoadedDiaryEntries _noEntries = (entries: [], hasMore: false);

  /// Runs one load at a time, so that calls during a load wait for it
  /// instead of loading the same entries again.
  final _load = AsyncCache<void>.ephemeral();

  @override
  FutureOr<LoadedDiaryEntries> build(String term) {
    final link = ref.keepAlive();
    ref.listen(diarySearchSessionProvider, (_, place) {
      if (place.term != term) {
        link.close();
      }
    }, fireImmediately: true);
    if (term.isEmpty) {
      return _noEntries;
    }
    return _search(offset: 0, limit: _pageSize);
  }

  /// Loads the next page of the entries.
  ///
  /// Does nothing when no entries are loaded or none are left.
  Future<void> loadMore() => _load.fetch(() async {
    final loaded = state.value;
    if (loaded == null || !loaded.hasMore) {
      return;
    }
    final result = await AsyncValue.guard(() async {
      final next = await _search(
        offset: loaded.entries.length,
        limit: _pageSize,
      );
      return (
        entries: [...loaded.entries, ...next.entries],
        hasMore: next.hasMore,
      );
    });
    if (ref.mounted) {
      state = result;
    }
  });

  /// Loads the pages loaded so far again, so that they show the diaries as
  /// they are now.
  ///
  /// Searches again from the first page when no entries are loaded.
  Future<void> reload() => _load.fetch(() async {
    final loaded = state.value;
    if (loaded == null) {
      ref.invalidateSelf();
      return;
    }
    final pages = (loaded.entries.length / _pageSize).ceil();
    final result = await AsyncValue.guard(
      () => _search(offset: 0, limit: max(pages, 1) * _pageSize),
    );
    if (ref.mounted) {
      state = result;
    }
  });

  Future<LoadedDiaryEntries> _search({
    required int offset,
    required int limit,
  }) async {
    final entries = await ref
        .read(diaryQueryProvider)
        .searchDiaries(searchTerm: term, limit: limit, offset: offset);
    return (entries: entries, hasMore: entries.length == limit);
  }
}
